def main(out: str = "data/emails.jsonl") -> int:
    rows = [{"id": f"{label}-{i:02d}", "email": text, "intent": label}
            for label, texts in DATA.items() for i, text in enumerate(texts)]
    Path(out).write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    return len(rows)


if __name__ == "__main__":
    print(f"wrote {main()} rows")
